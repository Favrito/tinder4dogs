--comment: one latest decision per directed dog pair
CREATE TABLE dog_decision (
    id            BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    actor_dog_id  BIGINT      NOT NULL,
    target_dog_id BIGINT      NOT NULL,
    decision      VARCHAR(10) NOT NULL,
    CONSTRAINT pk_dog_decision PRIMARY KEY (id),
    CONSTRAINT fk_dog_decision_actor FOREIGN KEY (actor_dog_id)
        REFERENCES dog (id) ON DELETE CASCADE,
    CONSTRAINT fk_dog_decision_target FOREIGN KEY (target_dog_id)
        REFERENCES dog (id) ON DELETE CASCADE,
    CONSTRAINT uk_dog_decision_actor_target UNIQUE (actor_dog_id, target_dog_id)
);
